export class TennisDatasetLoader {
  private matches: HistoricalMatchRecord[] = []
  private players: Map<string, TennisPlayer> = new Map()

  constructor() {
    this.matches = [...BENCHMARK_HISTORICAL_MATCHES].sort(
      (a, b) => new Date(a.date).getTime() - new Date(b.date).getTime()
    )
    for (const [id, player] of Object.entries(TENNIS_PLAYERS_REGISTRY)) {
      this.players.set(id, player)
    }
  }

  public getMatches(): HistoricalMatchRecord[] {
    return [...this.matches]
  }

  public getMatchesBefore(date: string): HistoricalMatchRecord[] {
    const targetTime = new Date(date).getTime()
    return this.matches.filter((m) => new Date(m.date).getTime() < targetTime)
  }

  public getPlayer(id: string): TennisPlayer | undefined {
    return this.players.get(id)
  }

  public getPlayerByName(name: string): TennisPlayer | undefined {
    const normalized = name.toLowerCase().trim()
    for (const player of this.players.values()) {
      if (player.name.toLowerCase().includes(normalized)) {
        return player
      }
    }
    return undefined
  }

  public getAllPlayers(): TennisPlayer[] {
    return Array.from(this.players.values())
  }

  public getProvenance(): typeof TENNIS_DATASET_ATTRIBUTION {
    return TENNIS_DATASET_ATTRIBUTION
  }
}

export const defaultTennisDataset = new TennisDatasetLoader()
